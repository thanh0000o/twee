"""Writes src/lib/media-ratios.ts: width/height of every gallery photo and video.

The scattered galleries use these to reserve each photo's space before it loads, so the layout
is set once and nothing jumps while scrolling. Run again after adding photos:
    python3 scripts/media-ratios.py
"""
import json, os, subprocess, sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..', 'src', 'assets')
FOLDERS = ['artwork', 'artwork/videos', 'visualisations', 'visualisations/fungi']
ratios = {}
for folder in FOLDERS:
    path = os.path.join(ROOT, folder)
    if not os.path.isdir(path):
        continue
    for name in sorted(os.listdir(path)):
        file = os.path.join(path, name)
        if not os.path.isfile(file):
            continue
        ext = name.rsplit('.', 1)[-1].lower()
        try:
            if ext in ('jpg', 'jpeg', 'png', 'webp', 'gif'):
                with Image.open(file) as im:
                    from PIL import ImageOps
                    w, h = ImageOps.exif_transpose(im).size
            elif ext in ('mp4', 'webm', 'mov'):
                out = subprocess.check_output(['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-show_entries',
                                               'stream=width,height:stream_side_data=rotation', '-of', 'json', file])
                s = json.loads(out)['streams'][0]
                w, h = s['width'], s['height']
                rot = abs(int(next((d.get('rotation', 0) for d in s.get('side_data_list', [])), 0)))
                if rot in (90, 270):
                    w, h = h, w
            else:
                continue
        except Exception as error:
            print('skip', file, error, file=sys.stderr)
            continue
        ratios[f'{folder}/{name}'] = round(w / h, 4)

out = os.path.join(os.path.dirname(__file__), '..', 'src', 'lib', 'media-ratios.ts')
with open(out, 'w') as f:
    f.write('// Generated by scripts/media-ratios.py: width / height of each gallery file, by path under src/assets.\n')
    f.write('export const MEDIA_RATIOS: Record<string, number> = ')
    f.write(json.dumps(ratios, indent=2, sort_keys=True))
    f.write(';\n')
print(len(ratios), 'files')
